"""
Shared feature engineering for the Smart Electricity Consumption project.

Both train_model.py and dashboard.py import from this file, so the features
used for TRAINING and the features used for the live NEXT-HOUR prediction are
generated by the same definitions. This is what prevents train/serve skew.

Definitions (verified against the original Colab notebook: they reproduce the
original model's saved predictions in actual_vs_predicted.csv exactly):

  * Calendar features describe the hour being predicted (known in advance).
  * lag_k  = consumption k rows BEFORE the target row (positional shift).
  * rolling_mean_w = mean of the w rows BEFORE the target row, i.e.
                     series.shift(1).rolling(w).mean()  -> the current/target
                     value is never inside its own window (no data leakage).
  * Chronological split: first 80 % of rows train, last 20 % test, no shuffling.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

TARGET = "consumption_kwh"

FEATURES = [
    "hour", "day_of_week", "month", "is_weekend",
    "lag_1", "lag_2", "lag_3", "lag_24", "lag_48", "lag_168",
    "rolling_mean_24", "rolling_mean_168",
]

LAGS = (1, 2, 3, 24, 48, 168)
ROLLING_WINDOWS = (24, 168)
TRAIN_FRACTION = 0.80
MIN_HISTORY = 168  # rows needed to build every feature for the next hour


def load_series(path: str | Path) -> pd.Series:
    """Read hourly_consumption.csv -> clean, sorted, datetime-indexed Series."""
    df = pd.read_csv(path)
    time_col = "datetime" if "datetime" in df.columns else df.columns[0]
    df[time_col] = pd.to_datetime(df[time_col])
    df = df.set_index(time_col)
    s = pd.to_numeric(df[TARGET], errors="coerce").dropna().sort_index()
    s = s[~s.index.duplicated(keep="first")]
    s.name = TARGET
    return s


def make_features(series: pd.Series) -> pd.DataFrame:
    """Build the supervised-learning table: TARGET + the 12 FEATURES."""
    d = pd.DataFrame({TARGET: series})
    d["hour"] = d.index.hour
    d["day_of_week"] = d.index.dayofweek
    d["month"] = d.index.month
    d["is_weekend"] = (d.index.dayofweek >= 5).astype(int)
    for k in LAGS:
        d[f"lag_{k}"] = series.shift(k)
    past = series.shift(1)  # only information available BEFORE the target hour
    for w in ROLLING_WINDOWS:
        d[f"rolling_mean_{w}"] = past.rolling(w).mean()
    return d.dropna()[[TARGET] + FEATURES]


def chronological_split(df: pd.DataFrame, train_fraction: float = TRAIN_FRACTION):
    """Chronological split (no shuffling): first 80 % train, last 20 % test."""
    cut = int(len(df) * train_fraction)
    return df.iloc[:cut], df.iloc[cut:]


def next_hour_features(series: pd.Series):
    """
    Feature row for the hour AFTER the last observation.
    Uses only readings that already exist, with the same definitions as
    make_features(). Returns (timestamp, 1-row DataFrame[FEATURES]).
    """
    if len(series) < MIN_HISTORY:
        raise ValueError(f"Need at least {MIN_HISTORY} hourly observations.")
    t = series.index[-1] + pd.Timedelta(hours=1)
    row = {
        "hour": t.hour,
        "day_of_week": t.dayofweek,
        "month": t.month,
        "is_weekend": int(t.dayofweek >= 5),
        **{f"lag_{k}": float(series.iloc[-k]) for k in LAGS},
        "rolling_mean_24": float(series.iloc[-24:].mean()),
        "rolling_mean_168": float(series.iloc[-168:].mean()),
    }
    return t, pd.DataFrame([row])[FEATURES]